def tab(sync, url, essential=False, group=None, label=None):
    t = {
        "pinned": True,
        "zenEssential": essential,
        "zenSyncId": sync,
        "zenWorkspace": SPACE,
        "userContextId": 0,
        "index": 1,
        "entries": [{"url": "https://moved.example/", "title": "Moved"}],
        "_zenPinnedInitialState": {"entry": {"url": url, "title": "Page"}},
    }
    if group:
        t["groupId"] = group
    if label:
        t["zenStaticLabel"] = label
    return t


